create or replace function public.club_plan_limit(plan_name text, metric text)
returns integer
language sql
immutable
set search_path = public
as $$
  select case lower(coalesce(metric, ''))
    when 'photos' then
      case lower(coalesce(plan_name, 'free'))
        when 'premium' then 6
        when 'basico' then 6
        else 4
      end
    when 'videos' then
      case lower(coalesce(plan_name, 'free'))
        when 'premium' then 3
        when 'basico' then 3
        else 0
      end
    when 'stories' then
      case lower(coalesce(plan_name, 'free'))
        when 'premium' then 1
        else 0
      end
    else 0
  end;
$$;

grant execute on function public.club_plan_limit(text, text) to anon, authenticated;

create or replace function public.enforce_club_plan_access()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  requested_plan text := lower(coalesce(new.plan_slug, 'free'));
  active_subscription record;
begin
  if requested_plan not in ('free', 'basico', 'premium') then
    raise exception 'Plano invalido para anuncio.';
  end if;

  if requested_plan = 'free' then
    new.plan_slug := 'free';
    new.plan_status := 'free';
    new.plan_expires_at := null;
    new.sorting_weight := 0;
    new.is_premium := false;
    new.is_featured := false;
    new.stories_enabled := false;
    new.stories_count := 0;
    return new;
  end if;

  if not public.is_admin() then
    select subscription.plan_slug,
           subscription.billing_period,
           subscription.current_period_end
      into active_subscription
      from public.club_subscriptions subscription
      where subscription.user_id = new.user_id
        and subscription.plan_slug = requested_plan
        and subscription.status = 'active'
        and subscription.current_period_end > now()
      order by subscription.current_period_end desc
      limit 1;

    if not found then
      raise exception 'Plano pago ainda nao confirmado.';
    end if;

    new.plan_expires_at := active_subscription.current_period_end;
  end if;

  new.plan_status := 'active';
  new.sorting_weight := case requested_plan
    when 'premium' then 20
    when 'basico' then 10
    else 0
  end;
  new.is_premium := requested_plan = 'premium';
  new.is_featured := false;

  if requested_plan <> 'premium' then
    new.stories_enabled := false;
    new.stories_count := 0;
  elsif coalesce(new.stories_count, 0) > 1 then
    raise exception 'Plano Premium permite no maximo 1 story.';
  end if;

  return new;
end;
$$;

update public.ads
set
  plan_slug = case
    when is_premium then 'premium'
    when coalesce(plan_slug, '') in ('basico', 'premium', 'free') then plan_slug
    else 'free'
  end,
  plan_status = case
    when coalesce(plan_slug, 'free') = 'free' then 'free'
    else coalesce(plan_status, 'active')
  end,
  sorting_weight = case
    when is_premium or coalesce(plan_slug, '') = 'premium' then 20
    when coalesce(plan_slug, '') = 'basico' then 10
    else 0
  end;

drop trigger if exists enforce_club_plan_access on public.ads;
create trigger enforce_club_plan_access
before insert or update of plan_slug, stories_enabled, stories_count, user_id on public.ads
for each row execute function public.enforce_club_plan_access();

create or replace function public.enforce_club_media_limits()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  media_count integer;
  owner_plan text;
  allowed_count integer;
begin
  select coalesce(ad.plan_slug, 'free')
    into owner_plan
    from public.ads ad
    where ad.id = new.ad_id;

  owner_plan := coalesce(owner_plan, 'free');

  if tg_table_name = 'ad_photos' then
    allowed_count := public.club_plan_limit(owner_plan, 'photos');

    select count(*)
      into media_count
      from public.ad_photos
      where ad_id = new.ad_id
        and id is distinct from new.id;

    if media_count >= allowed_count then
      raise exception 'Este plano permite no maximo % fotos.', allowed_count;
    end if;
  elsif tg_table_name = 'ad_videos' then
    allowed_count := public.club_plan_limit(owner_plan, 'videos');

    if allowed_count <= 0 then
      raise exception 'Este plano nao permite videos.';
    end if;

    if new.duration_seconds is not null and new.duration_seconds > 10 then
      raise exception 'Cada video pode ter no maximo 10 segundos.';
    end if;

    select count(*)
      into media_count
      from public.ad_videos
      where ad_id = new.ad_id
        and id is distinct from new.id;

    if media_count >= allowed_count then
      raise exception 'Este plano permite no maximo % videos.', allowed_count;
    end if;
  elsif tg_table_name = 'ad_audios' then
    if new.duration_seconds is not null and new.duration_seconds > 8 then
      raise exception 'O audio pode ter no maximo 8 segundos.';
    end if;

    select count(*)
      into media_count
      from public.ad_audios
      where ad_id = new.ad_id
        and id is distinct from new.id;

    if media_count >= 1 then
      raise exception 'Cada anuncio pode ter no maximo 1 audio.';
    end if;
  end if;

  return new;
end;
$$;
