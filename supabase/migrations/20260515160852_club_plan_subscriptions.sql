create table if not exists public.club_subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  plan_slug text not null,
  billing_period text not null,
  status text not null default 'pending',
  starts_at timestamptz,
  current_period_end timestamptz,
  canceled_at timestamptz,
  external_reference text,
  external_payment_id text,
  external_preference_id text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint club_subscriptions_plan_slug_check
    check (plan_slug in ('basico', 'premium')),
  constraint club_subscriptions_billing_period_check
    check (billing_period in ('weekly', 'monthly')),
  constraint club_subscriptions_status_check
    check (status in ('pending', 'active', 'past_due', 'canceled', 'expired'))
);

create index if not exists club_subscriptions_user_status_period_idx
  on public.club_subscriptions(user_id, status, current_period_end desc);

create unique index if not exists club_subscriptions_external_reference_unique_idx
  on public.club_subscriptions(external_reference);

